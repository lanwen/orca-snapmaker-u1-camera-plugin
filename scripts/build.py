"""Build a self-contained Orca plugin and its release checksum."""

import argparse
import hashlib
import json
from pathlib import Path
import tomllib


ROOT = Path(__file__).resolve().parents[1]
PAGE_MARKER = 'PAGE = "__CAMERA_HTML__"'
HTTP_IMPORT = 'from http_client import HttpClient, LightCommand, ObjectQuery, printer_url'


def build(output_dir=ROOT / "dist", release_tag=None):
    project = tomllib.loads((ROOT / "pyproject.toml").read_text(encoding="utf-8"))["project"]
    if release_tag is not None and release_tag != "v" + project["version"]:
        raise ValueError("Release tag must match project version v" + project["version"])
    if release_tag is not None and project["version"].endswith(".dev0"):
        raise ValueError("Development versions cannot be published as releases")
    source = (ROOT / "src/plugin.py").read_text(encoding="utf-8")
    if source.count(PAGE_MARKER) != 1:
        raise ValueError("Plugin source must contain exactly one HTML placeholder")
    if source.count(HTTP_IMPORT) != 1:
        raise ValueError("Plugin source must contain exactly one HTTP client import")
    transport = (ROOT / "src/http_client.py").read_text(encoding="utf-8")
    source = source.replace(HTTP_IMPORT, transport)
    page = (ROOT / "src/camera.html").read_text(encoding="utf-8")
    metadata = [
        '# /// script',
        '# requires-python = ' + json.dumps(project["requires-python"]),
        '# dependencies = ' + json.dumps(project["dependencies"]),
        '#',
        '# [tool.orcaslicer.plugin]',
        '# name = ' + json.dumps(project["name"]),
        '# description = ' + json.dumps(project["description"]),
        '# author = ' + json.dumps(project["authors"][0]["name"]),
        '# version = ' + json.dumps(project["version"]),
        '# ///',
        '# Generated by scripts/build.py. Edit src/ and pyproject.toml.',
        '',
    ]
    license_text = (ROOT / "LICENSE").read_text(encoding="utf-8")
    license_notice = "\n".join("# " + line if line else "#" for line in license_text.splitlines())
    built = "\n".join(metadata) + license_notice + "\n\n" + source.replace(PAGE_MARKER, "PAGE = " + repr(page))
    filename = project["name"] + "_any.py"
    compile(built, filename, "exec")
    output_dir = Path(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)
    artifact = output_dir / filename
    artifact.write_bytes(built.encode("utf-8"))
    checksum = hashlib.sha256(artifact.read_bytes()).hexdigest()
    (output_dir / "SHA256SUMS").write_text(checksum + "  " + filename + "\n", encoding="utf-8")
    return artifact


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--release-tag", help="Require this tag to match the project version")
    args = parser.parse_args()
    print(build(release_tag=args.release_tag))
